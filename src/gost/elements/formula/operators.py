"""Таблицы символов, по которым конвертер MathML → OMML выбирает конструкцию.

MathML не различает роли: и знак суммы, и скобка, и знак вектора приходят одним
и тем же тегом ``<mo>``. Роль определяется символом, поэтому разбор опирается на
эти наборы.
"""

# Знаки, которые в OMML разворачиваются в m:nary (оператор с пределами), а не в
# обычные верхний/нижний индексы. Значение — где ставить пределы (m:limLoc).
#
# У суммы и произведения пределы идут над и под знаком, у интегралов — сбоку;
# это устоявшаяся типографская норма, и так же ведёт себя редактор формул Word.
# Расположение задаётся именно знаком, а не режимом разбора LaTeX: внутри дроби
# latex2mathml переключается на строчный стиль, и сумма пришла бы с пределами
# сбоку даже в выключной формуле.
NARY_LIMITS = {
    "∑": "undOvr",  # ∑ сумма
    "∏": "undOvr",  # ∏ произведение
    "∐": "undOvr",  # ∐ копроизведение
    "⋀": "undOvr",  # ⋀ конъюнкция
    "⋁": "undOvr",  # ⋁ дизъюнкция
    "⋂": "undOvr",  # ⋂ пересечение
    "⋃": "undOvr",  # ⋃ объединение
    "∫": "subSup",  # ∫ интеграл
    "∬": "subSup",  # ∬ двойной
    "∭": "subSup",  # ∭ тройной
    "∮": "subSup",  # ∮ контурный
    "∯": "subSup",  # ∯
    "∰": "subSup",  # ∰
}

# Скобки. Порядок пар важен: индекс открывающей = индекс закрывающей.
_OPENING = "([{⟨⌈⌊‖|"
_CLOSING = ")]}⟩⌉⌋‖|"

BRACKET_PAIRS = dict(zip(_OPENING, _CLOSING))
OPENING_CHARS = frozenset(_OPENING)
CLOSING_CHARS = frozenset(_CLOSING)

# Знаки акцентов: что отдаёт latex2mathml → что нужно записать в m:chr.
#
# Отдаёт он отдельно стоящие символы («^», «~»), а OMML ждёт комбинирующие
# диакритики: только они позиционируются НАД буквой. С обычным «^» Word нарисует
# крышку рядом с переменной, а не над ней.
#
# accent="true" latex2mathml ставит не всегда (у \vec его нет), поэтому набор
# нужен и сам по себе, а не только как дополнение к атрибуту.
ACCENT_CHARS = {
    "^": "̂",   # \hat, \widehat
    "~": "̃",   # \tilde, \widetilde
    "˙": "̇",  # \dot
    "¨": "̈",  # \ddot
    "¯": "̅",  # \bar
    "→": "⃗",  # \vec
    "´": "́",  # \acute
    "`": "̀",   # \grave
    "ˇ": "̌",  # \check
    "˘": "̆",  # \breve
}

# Черта над или под всем выражением (\overline, \underline). В отличие от акцента
# растягивается по ширине базы, поэтому это m:bar, а не m:acc.
BAR_CHARS = frozenset("―‾_")

# Скобки-обхваты: \underbrace / \overbrace дают m:groupChr.
# Значение — положение символа относительно содержимого (m:vertJc).
GROUP_CHARS = {
    "⏟": "bot",  # ⏟ \underbrace
    "⏞": "top",  # ⏞ \overbrace
    "⎵": "bot",  # ⏵ нижняя скобка
    "⎴": "top",  # ⏴ верхняя скобка
}
